import { z } from 'zod';
import type { ContentTypeSchema, FieldDefinition, ValidationResult } from './types.js';

/**
 * Converts a single FieldDefinition into its corresponding Zod schema validator.
 */
export function buildFieldZodSchema(field: FieldDefinition): z.ZodTypeAny {
  let schema: z.ZodTypeAny;

  switch (field.type) {
    case 'string': {
      let strSchema = z.string();
      if (field.validation?.min !== undefined) {
        strSchema = strSchema.min(field.validation.min);
      }
      if (field.validation?.max !== undefined) {
        strSchema = strSchema.max(field.validation.max);
      }
      if (field.validation?.pattern) {
        strSchema = strSchema.regex(new RegExp(field.validation.pattern));
      }
      schema = strSchema;
      break;
    }

    case 'number': {
      let numSchema = z.number();
      if (field.validation?.min !== undefined) {
        numSchema = numSchema.min(field.validation.min);
      }
      if (field.validation?.max !== undefined) {
        numSchema = numSchema.max(field.validation.max);
      }
      schema = numSchema;
      break;
    }

    case 'boolean': {
      schema = z.boolean();
      break;
    }

    case 'date': {
      schema = z.string().datetime().or(z.date());
      break;
    }

    case 'select': {
      if (field.options && field.options.length > 0) {
        schema = z.enum(field.options as [string, ...string[]]);
      } else {
        schema = z.string();
      }
      break;
    }

    case 'relation': {
      schema = z.string().uuid();
      break;
    }

    case 'media': {
      schema = z.object({
        url: z.string().url(),
        title: z.string().optional(),
        mimeType: z.string().optional(),
        size: z.number().optional(),
      });
      break;
    }

    case 'encrypted': {
      // String representing encrypted ciphertext or blind-indexed token
      schema = z.string();
      break;
    }

    case 'json':
    default: {
      schema = z.record(z.unknown());
      break;
    }
  }

  if (!field.required) {
    schema = schema.optional();
  }

  return schema;
}

/**
 * Compiles a ContentTypeSchema into an executable Zod schema.
 */
export function compileSchemaToZod(contentTypeSchema: ContentTypeSchema): z.ZodObject<Record<string, z.ZodTypeAny>> {
  const shape: Record<string, z.ZodTypeAny> = {};

  for (const field of contentTypeSchema.fields) {
    shape[field.key] = buildFieldZodSchema(field);
  }

  return z.object(shape);
}

/**
 * Validates dynamic record data against a content type definition.
 */
export function validateRecordData(
  contentTypeSchema: ContentTypeSchema,
  data: unknown,
): ValidationResult {
  const validator = compileSchemaToZod(contentTypeSchema);
  const result = validator.safeParse(data);

  if (result.success) {
    return { success: true, data: result.data };
  }

  return {
    success: false,
    errors: result.error.errors.map((err) => ({
      field: err.path.join('.'),
      message: err.message,
    })),
  };
}

/**
 * Dedicated validator for AI proposals.
 * Guarantees that any proposal generated by an AI assistant conforms strictly to the schema
 * before human review or execution.
 */
export function validateAiProposal(
  contentTypeSchema: ContentTypeSchema,
  proposalData: unknown,
): ValidationResult {
  return validateRecordData(contentTypeSchema, proposalData);
}
